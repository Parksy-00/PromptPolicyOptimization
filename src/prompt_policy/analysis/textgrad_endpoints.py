def cached_context(record, cache_root, prompt_ids, response_ids):
    """Reuse only a verified exact request and fixed response, never a matching name."""
    path = cache_root / record["token_file"]
    if file_sha256(path) != record["sha256"]:
        raise ValueError("Cached token-file checksum differs")
    with np.load(path) as data:
        if not np.array_equal(data["prompt_ids"], prompt_ids):
            raise ValueError("Cached prompt IDs differ")
        if not np.array_equal(data["response_ids"], response_ids):
            raise ValueError("Cached response IDs differ")
        metrics = summarize_arrays(data["scores"])
    if metrics != record["metrics"] or digest(response_ids) != record["response_sha256"]:
        raise ValueError("Cached score aggregation differs")
    return path


def build_inputs(config, tokenizer):
    formats = {s.get("task_format", "textgrad_native_v1") for s in config["sources"]}
    if formats == {"dspy_chat_adapter_v1"}:
        return build_legacy_inputs(config, tokenizer)
    if formats != {"textgrad_native_v1"}:
        raise ValueError("Use one explicitly supported task format per endpoint execution")
    if any("response_origins" in source for source in config["sources"]):
        raise ValueError("Candidate-origin input reader currently supports historical DSPy DAPO only")
    original_plan, jobs, _, _ = prepare(config, tokenizer)
    selected, work = [], []
    for source in config["sources"]:
        native = Path(source["root"]) / "native"
        candidates = {r["candidate_id"]: r for r in read_jsonl(native / "candidates.jsonl")}
        summary = json.loads((native / "summary.json").read_text())
        final_id = source["final_candidate"]
        if summary["best_candidate_id"] != final_id:
            raise ValueError("Requested final candidate differs from original selection")
        base, final = candidates["0"], candidates[final_id]
        if not base["is_base"] or not final["accepted"]:
            raise ValueError("Invalid base or selected candidate")
        path, current = [final_id], final
        while current["parent_ids"]:
            if len(current["parent_ids"]) != 1 or current["parent_ids"][0] in path:
                raise ValueError("Invalid original parent chain")
            current = candidates[current["parent_ids"][0]]
            path.append(current["candidate_id"])
        if path[-1] != "0":
            raise ValueError("Selected prompt does not descend from base")
        repeat = next(s for s in original_plan["sources"] if s["run_id"] == Path(source["root"]).name)
        repeated = {r["candidate_id"]: r for r in repeat["repeat_validation"]["candidates"]}
        selected.append(
            {
                "source": source["name"],
                "run_id": Path(source["root"]).name,
                "base_id": "0",
                "selected_id": final_id,
                "actual_accepted_path": path[::-1],
                "base_validation": base["validation_score"],
                "selected_validation": final["validation_score"],
                "base_repeat8_validation": repeated["0"]["mean_success_rate"],
                "selected_repeat8_validation": repeated[final_id]["mean_success_rate"],
                "base_instruction": base["instruction"],
                "selected_instruction": final["instruction"],
            }
        )
        for job in jobs.values():
            if job["source"] != source["name"] or job["split"] != "validation" or "0" not in job["contexts"]:
                continue
            messages = [dict(m) for m in job["messages"]]
            if messages[0]["content"] != base["instruction"]:
                raise ValueError("Reference response was not generated by the base prompt")
            messages[0]["content"] = final["instruction"]
            prefix = flat_ids(
                tokenizer.apply_chat_template(
                    messages, tokenize=True, add_generation_prompt=True, enable_thinking=True
                )
            )
            if len(prefix) + len(job["response_ids"]) > config["model"]["max_context_tokens"]:
                raise ValueError("Endpoint context overflow")
            work.append({**job, "contexts": {"0": job["contexts"]["0"], final_id: prefix}})
    return original_plan["sources"], selected, work


def legacy_dapo_score(raw_text, gold_answer):
    """Historical DSPy DAPO field extraction and Python-int score, checked against saved rows."""
    sections = [(None, [])]
    for line in (raw_text or "").splitlines():
        match = re.match(r"\[\[ ## (\w+) ## \]\]", line.strip())
        if match is None:
            sections[-1][1].append(line)
        else:
            remaining = line[match.end() :].strip()
            sections.append((match[1], [remaining] if remaining else []))
    fields = {}
    for name, lines in sections:
        if name in ("reasoning", "answer") and name not in fields:
            fields[name] = "\n".join(lines).strip()
    if set(fields) != {"reasoning", "answer"}:
        return 0.0, 0.0
    try:
        prediction = int(fields["answer"])
    except (TypeError, ValueError):
        return 0.0, 0.0
    return float(prediction == int(gold_answer)), 1.0


def instruction_wrapper(system, instruction):
    """Identify the exact preserved DSPy wrapper around its indented instruction."""
    tail = instruction.replace("\n", "\n        ")
    if not tail or not system.endswith(tail):
        raise ValueError("Captured system message does not contain the declared DSPy instruction")
    return system[: -len(tail)]


def build_legacy_inputs(config, tokenizer):
    sources, endpoints, jobs = [], [], []
    for source in config["sources"]:
        if source["benchmark"] != "DAPOMathBench":
            raise ValueError("Historical DSPy endpoint reader currently supports DAPO only")
        root = Path(source["root"]).resolve()
        native = root / "native"
        evaluation = root / "evaluations" / source["repeat_evaluation"]
        cfg = json.loads((native / "config.json").read_text())
        summary = json.loads((native / "summary.json").read_text())
        if summary["status"] != "complete":
            raise ValueError("Historical source is incomplete")
        prov = cfg["provenance"]
        if prov.get("task_format", "dspy_chat_adapter_v1") != "dspy_chat_adapter_v1":
            raise ValueError("Source is not the historical DSPy task format")
        if prov["task_model"]["revision"] != config["model"]["revision"]:
            raise ValueError("Historical source model revision mismatch")
        if prov["scorer"] != "common.evaluation.dapo_math.score_dapo_math_completion":
            raise ValueError("Unexpected historical scoring contract")
        final_id = source["final_candidate"]
        if summary["best_candidate_id"] != final_id:
            raise ValueError("Endpoint differs from original validation selection")
        candidates = {r["candidate_id"]: r for r in read_jsonl(native / "candidates.jsonl")}
        base, final = candidates["0"], candidates[final_id]
        if not base["is_base"] or not final["accepted"]:
            raise ValueError("Invalid source endpoints")
        path, current = [final_id], final
        while current["parent_ids"]:
            if len(current["parent_ids"]) != 1 or current["parent_ids"][0] in path:
                raise ValueError("Invalid selected prompt lineage")
            current = candidates[current["parent_ids"][0]]
            path.append(current["candidate_id"])
        if path[-1] != "0":
            raise ValueError("Selected prompt does not descend from base")
        splits = json.loads((native / "splits.json").read_text())
        examples = {split: {e["sample_id"]: e for e in rows} for split, rows in splits.items()}
        captures = {cid: {} for cid in candidates}
        native_rows = read_jsonl(native / "responses.jsonl")
        for row in native_rows:
            if row["split"] not in {"train", "validation"}:
                raise ValueError("Unexpected test responses in optimization source")
            ex = examples[row["split"]][row["sample_id"]]
            score, format_success = legacy_dapo_score(row.get("completion"), ex["answer"])
            if score != row["score"] or format_success != row["format_success"]:
                raise ValueError("Historical scorer does not reproduce a saved reward/format result")
            if row["split"] == "validation":
                if row["sample_id"] in captures[row["candidate_id"]]:
                    raise ValueError("Duplicate original validation response")
                captures[row["candidate_id"]][row["sample_id"]] = row
        for cid, rows in captures.items():
            if set(rows) != set(examples["validation"]):
                raise ValueError("Incomplete historical validation capture")
            if (
                abs(np.mean([r["score"] for r in rows.values()]) - candidates[cid]["validation_score"])
                > 1e-12
            ):
                raise ValueError("Historical validation accuracy mismatch")
        em = json.loads((evaluation / "manifest.json").read_text())
        if em["source_run_id"] != root.name or em["best_candidate_id"] != final_id:
            raise ValueError("Historical repeat evaluation attribution mismatch")
        for name, sha in em["source_sha256"].items():
            if file_sha256(native / name) != sha:
                raise ValueError("Historical evaluation input hash mismatch")
        repeat = json.loads((evaluation / "validation_summary.json").read_text())
        if repeat["status"] != "complete":
            raise ValueError("Repeat evaluation incomplete")
        repeated = {r["candidate_id"]: r for r in repeat["candidates"]}
        inventory = {
            str(p.relative_to(root)): file_sha256(p)
            for p in [
                *(
                    native / name
                    for name in [
                        "config.json",
                        "summary.json",
                        "candidates.jsonl",
                        "splits.json",
                        "responses.jsonl",
                    ]
                ),
                evaluation / "manifest.json",
                evaluation / "validation_summary.json",
            ]
        }
        sources.append(
            {
                "run_id": root.name,
                "root": str(root),
                "benchmark": source["benchmark"],
                "task_format": "dspy_chat_adapter_v1",
                "seed": cfg["seed"],
                "files_sha256": inventory,
                "reward_checks": len(native_rows),
                "repeat_validation": repeat,
                "scorer_reference_sha256": file_sha256(Path(source["scorer_reference"])),
            }
        )
        endpoint = {
            "source": source["name"],
            "run_id": root.name,
            "base_id": "0",
            "selected_id": final_id,
            "task_format": "dspy_chat_adapter_v1",
            "actual_accepted_path": path[::-1],
            "base_validation": base["validation_score"],
            "selected_validation": final["validation_score"],
            "base_repeat8_validation": repeated["0"]["mean_success_rate"],
            "selected_repeat8_validation": repeated[final_id]["mean_success_rate"],
            "base_instruction": base["instruction"],
            "selected_instruction": final["instruction"],
        }
        origins = source.get("response_origins", ["0"])
        if not origins or len(set(origins)) != len(origins) or any(cid not in candidates for cid in origins):
            raise ValueError("Response origins must be distinct captured candidates")
        if "response_origins" in source:
            endpoint["response_origins"] = origins
            endpoint["origin_candidates"] = {
                cid: {
                    "accepted": candidates[cid]["accepted"],
                    "on_selected_path": cid in path,
                    "validation_accuracy": candidates[cid]["validation_score"],
                    "parent_ids": candidates[cid]["parent_ids"],
                }
                for cid in origins
            }
        endpoints.append(endpoint)
        for origin_id in origins:
            for sample_id, old in captures[origin_id].items():
                new = captures[final_id][sample_id]
                old_messages, new_messages = old["messages"], new["messages"]
                if old_messages[1:] != new_messages[1:]:
                    raise ValueError("Endpoint requests differ in question/history")
                if instruction_wrapper(
                    old_messages[0]["content"], candidates[origin_id]["instruction"]
                ) != instruction_wrapper(new_messages[0]["content"], final["instruction"]):
                    raise ValueError("Endpoint DSPy wrappers differ")
                contexts = {}
                context_rows = {"0": captures["0"][sample_id], final_id: new}
                if source.get("include_origin_context", False):
                    context_rows[origin_id] = old
                for cid, row in context_rows.items():
                    request = row["provider_call"]["request"]
                    if request["messages"] != row["messages"]:
                        raise ValueError("Actual request differs from saved endpoint messages")
                    if row["messages"][1:] != old_messages[1:] or instruction_wrapper(
                        row["messages"][0]["content"], candidates[cid]["instruction"]
                    ) != instruction_wrapper(
                        old_messages[0]["content"], candidates[origin_id]["instruction"]
                    ):
                        raise ValueError("Scoring context changes question/history or wrapper")
                    for key, expected in [
                        ("temperature", 0.6),
                        ("top_p", 0.95),
                        ("top_k", 20),
                        ("max_tokens", 16384),
                    ]:
                        if request.get(key) != expected:
                            raise ValueError("Historical request sampling settings differ")
                    prefix = flat_ids(
                        tokenizer.apply_chat_template(
                            row["messages"], tokenize=True, add_generation_prompt=True, enable_thinking=True
                        )
                    )
                    if len(prefix) != row["usage"]["prompt_tokens"]:
                        raise ValueError("Captured endpoint prompt token count differs")
                    contexts[cid] = prefix
                ids, audit = reconstruct(old, tokenizer)
                if any(
                    len(prefix) + len(ids) > config["model"]["max_context_tokens"]
                    for prefix in contexts.values()
                ):
                    raise ValueError("Historical endpoint context overflow")
                jobs.append(
                    {
                        "row_key": source["name"] + ":" + str(old["call_id"]),
                        "source": source["name"],
                        "origin_id": origin_id,
                        "sample_id": sample_id,
                        "split": "validation",
                        "response_ids": ids,
                        "reward": old["score"],
                        "finish_reason": old["finish_reason"],
                        "audit": audit,
                        "messages": old_messages,
                        "contexts": contexts,
                    }
                )
    return sources, endpoints, jobs


def summarize_endpoint(rows, repeats, rng):
    result = {"questions": len(rows), "successful_questions": sum(r["reward"] == 1 for r in rows)}
    for metric in ["t1", "t06"]:
        for kind in ["sum", "mean"]:
            result[f"reward_weighted_{metric}_{kind}"] = float(
                np.mean([r["reward"] * r[f"delta_{metric}_{kind}"] for r in rows])
            )
    good = [r for r in rows if r["reward"] == 1]
    result["successful_sequence_increases"] = sum(r["delta_t1_sum"] > 0 for r in good)
    clean = [r for r in rows if r["finish_reason"] == "stop" and r["count_match"]]
    result["stop_countmatched_questions"] = len(clean)
    result["stop_countmatched_weighted_t1_sum"] = (
        float(np.mean([r["reward"] * r["delta_t1_sum"] for r in clean])) if clean else None
    )
    values = np.array([r["reward"] * r["delta_t1_sum"] for r in rows])
    bootstrap = [rng.choice(values, len(values), replace=True).mean() for _ in range(repeats)]
    result["conditional_ci_low"], result["conditional_ci_high"] = map(
        float, np.quantile(bootstrap, [0.025, 0.975])
    )
    return result


def origin_contrast_row(job, reference_id, selected_id, cache):
    old = cache[job["row_key"] + ":" + reference_id]
    new = cache[job["row_key"] + ":" + selected_id]
    row = {
        "source": job["source"],
        "row_key": job["row_key"],
        "sample_id": job["sample_id"],
        "origin_id": job["origin_id"],
        "reference_id": reference_id,
        "selected_id": selected_id,
        "reward": job["reward"],
        "finish_reason": job["finish_reason"],
        "count_match": job["audit"]["expected_count_match"],
    }
    for metric in ["t1", "t06"]:
        for kind in ["sum", "mean"]:
            row[f"reference_{metric}_{kind}"] = old[metric][kind]
            row[f"selected_{metric}_{kind}"] = new[metric][kind]
            row[f"delta_{metric}_{kind}"] = new[metric][kind] - old[metric][kind]
    return row


def make_origin_report(output, plan, jobs, cache, statistics):
    trajectories, summaries = [], []
    rng = np.random.default_rng(statistics["bootstrap_seed"])
    for endpoint in plan["endpoints"]:
        final_id = endpoint["selected_id"]
        for origin_id in endpoint["response_origins"]:
            selected_jobs = [
                j for j in jobs if j["source"] == endpoint["source"] and j["origin_id"] == origin_id
            ]
            origin = endpoint["origin_candidates"][origin_id]
            status = (
                "base"
                if origin_id == "0"
                else "final"
                if origin_id == final_id
                else ("accepted_intermediate" if origin["on_selected_path"] else "rejected")
            )
            previous_stats = {}
            contrasts = [("base_to_final", "0")]
            if origin_id in selected_jobs[0]["contexts"]:
                contrasts.append(("origin_to_final", origin_id))
            for contrast, reference_id in contrasts:
                rows = [origin_contrast_row(j, reference_id, final_id, cache) for j in selected_jobs]
                trajectories.extend({"contrast": contrast, **r} for r in rows)
                if reference_id not in previous_stats:
                    stats = summarize_endpoint(rows, statistics["bootstrap_repeats"], rng)
                    for metric in ["t1", "t06"]:
                        for kind in ["sum", "mean"]:
                            for label, reward in [("success", 1), ("failure", 0)]:
                                values = [r[f"delta_{metric}_{kind}"] for r in rows if r["reward"] == reward]
                                stats[f"{label}_{metric}_{kind}"] = float(np.mean(values)) if values else None
                    stats["successful_token_mean_increases"] = sum(
                        r["reward"] == 1 and r["delta_t1_mean"] > 0 for r in rows
                    )
                    previous_stats[reference_id] = stats
                summaries.append(
                    {
                        "source": endpoint["source"],
                        "origin_id": origin_id,
                        "origin_status": status,
                        "origin_accepted": origin["accepted"],
                        "on_selected_path": origin["on_selected_path"],
                        "origin_validation_accuracy": origin["validation_accuracy"],
                        "selected_validation_accuracy": endpoint["selected_validation"],
                        "contrast": contrast,
                        "reference_id": reference_id,
                        "selected_id": final_id,
                        **previous_stats[reference_id],
                    }
                )
    write_csv(output / "trajectory_changes.csv", trajectories)
    write_csv(output / "origin_summary.csv", summaries)
    write_json(output / "summary.json", {"origin_contrasts": summaries})
    lines = [
        "# TextGrad candidate-origin likelihood comparisons",
        "",
        "Every origin contributes the same original validation questions with its own saved responses. "
        "Each fixed response is scored under base, final and (when requested) its own generating prompt. "
        "No new responses were generated. Rejected branches are descriptive comparisons, not actual accepted updates.",
        "",
        "G = mean original reward × (logp_final − logp_reference), T=1, nats/question. "
        "Failures contribute zero and all questions stay in the denominator.",
        "",
        "| Origin | Status | Successes / questions | G: final − base | G: final − origin | "
        "Success increases: final − base | Success increases: final − origin |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    for endpoint in plan["endpoints"]:
        for origin_id in endpoint["response_origins"]:
            base = next(
                r
                for r in summaries
                if r["source"] == endpoint["source"]
                and r["origin_id"] == origin_id
                and r["contrast"] == "base_to_final"
            )
            own = next(
                (
                    r
                    for r in summaries
                    if r["source"] == endpoint["source"]
                    and r["origin_id"] == origin_id
                    and r["contrast"] == "origin_to_final"
                ),
                None,
            )
            own_g = f"{own['reward_weighted_t1_sum']:+.4f}" if own else "not measured"
            own_increases = str(own["successful_sequence_increases"]) if own else "not measured"
            lines.append(
                f"| {origin_id} | {base['origin_status']} | {base['successful_questions']}/{base['questions']} | "
                f"{base['reward_weighted_t1_sum']:+.4f} | {own_g} | "
                f"{base['successful_sequence_increases']} | {own_increases} |"
            )
    lines += [
        "",
        "Final − base matches the GEPA endpoint contrast within each response origin. "
        "Final − origin measures preservation of each candidate's own responses. It is zero for the final "
        "origin by construction. A positive first contrast need not imply a positive second contrast.",
        "",
        "Each origin/contrast is reported separately; origins share questions and are not independent "
        "optimizer runs. Conditional question bootstrap intervals (2000 resamples, statistical seed 1729) "
        "do not include regeneration or across-run uncertainty. The duplicate base-origin contrasts "
        "reuse the same bootstrap result. Original validation selected the final prompt, so this is "
        "not held-out generalization evidence.",
        "",
        "Reward and format results reproduce the historical DSPy structured-field/Python-int scorer. "
        "Recorded request messages preserve wrapper and question/history. Original response IDs and "
        "EOS were not archived; response prefixes are reconstructed without adding EOS. Full-vocabulary "
        "T=1 and T=0.6 scores are not certified historical truncated-sampler probabilities. "
        "Normal-stop/count-matched sensitivity and success/failure conditional means are in origin_summary.csv.",
        "",
        "![Origin contrasts](origin_contrasts.png)",
        "",
        "[Origin metrics](origin_summary.csv) · [Per-response changes](trajectory_changes.csv) · "
        "[Reconstruction audit](reconstruction_audit.csv) · [Verification](verification.json)",
        "",
    ]
    (output / "README.md").write_text("\n".join(lines))
    plot_origin_report(output, summaries)
    return summaries


def plot_origin_report(output, summaries):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2), constrained_layout=True)
    for ax, contrast in zip(axes, ["base_to_final", "origin_to_final"], strict=True):
        rows = [r for r in summaries if r["contrast"] == contrast]
        for i, row in enumerate(rows):
            value = row["reward_weighted_t1_sum"]
            ax.errorbar(
                i,
                value,
                yerr=[
                    [max(0, value - row["conditional_ci_low"])],
                    [max(0, row["conditional_ci_high"] - value)],
                ],
                fmt="o",
                capsize=4,
                color="#8c8c8c" if row["origin_status"] == "rejected" else "#386ca7",
            )
        ax.axhline(0, color="black", linewidth=0.8)
        ax.set_xticks(
            range(len(rows)),
            [r["origin_id"] + ("*" if r["origin_status"] == "rejected" else "") for r in rows],
        )
        ax.set_xlabel("Generating candidate (* rejected)")
        ax.set_ylabel("Reward-weighted sequence logprob change (nats/question)")
        ax.set_title("Final − base" if contrast == "base_to_final" else "Final − generating candidate")
    fig.savefig(output / "origin_contrasts.png", dpi=180)
    fig.savefig(output / "origin_contrasts.pdf")
    plt.close(fig)


def make_report(output, plan, jobs, cache, statistics):
    if any("response_origins" in endpoint for endpoint in plan["endpoints"]):
        return make_origin_report(output, plan, jobs, cache, statistics)
    rows, endpoints = [], []
    rng = np.random.default_rng(statistics["bootstrap_seed"])
    for endpoint in plan["endpoints"]:
        selected_id = endpoint["selected_id"]
        chosen = []
        for job in jobs:
            if job["source"] != endpoint["source"]:
                continue
            old, new = [cache[job["row_key"] + ":" + cid] for cid in ["0", selected_id]]
            row = {
                "source": job["source"],
                "row_key": job["row_key"],
                "sample_id": job["sample_id"],
                "reward": job["reward"],
                "finish_reason": job["finish_reason"],
                "count_match": job["audit"]["expected_count_match"],
            }
            for metric in ["t1", "t06"]:
                for kind in ["sum", "mean"]:
                    row[f"base_{metric}_{kind}"] = old[metric][kind]
                    row[f"selected_{metric}_{kind}"] = new[metric][kind]
                    row[f"delta_{metric}_{kind}"] = new[metric][kind] - old[metric][kind]
            rows.append(row)
            chosen.append(row)
        endpoints.append(
            {
                **{k: v for k, v in endpoint.items() if not k.endswith("instruction")},
                **summarize_endpoint(chosen, statistics["bootstrap_repeats"], rng),
            }
        )
    write_csv(output / "trajectory_changes.csv", rows)
    write_json(output / "summary.json", {"endpoints": endpoints})
    write_csv(output / "endpoint_summary.csv", endpoints)
    lines = [
        "# TextGrad base → final selected prompt likelihood",
        "",
        "Fixed original base-validation responses, scored under both endpoint prompts. "
        "These are endpoint comparisons, not sums of successive update measurements.",
        "",
        "| Task / accepted path | Questions | Weighted Δ logprob T=1 (nats/question) | "
        "Conditional 95% CI | Original Δ accuracy (pp) | Repeat8 Δ accuracy (pp) |",
        "|---|---:|---:|---|---:|---:|",
    ]
    for e in endpoints:
        lines.append(
            f"| {e['source']}: {' → '.join(e['actual_accepted_path'])} | {e['questions']} | "
            f"{e['reward_weighted_t1_sum']:+.4f} | [{e['conditional_ci_low']:.4f}, {e['conditional_ci_high']:.4f}] | "
            f"{100 * (e['selected_validation'] - e['base_validation']):+.3f} | "
            f"{100 * (e['selected_repeat8_validation'] - e['base_repeat8_validation']):+.3f} |"
        )
    lines += [
        "",
        "Reward is the original binary source scorer result. G is mean r * (logp_selected - logp_base). "
        "Failures contribute zero; the denominator includes all questions. T=0.6, token means and "
        "normal-stop/count-matched sensitivity appear in endpoint_summary.csv.",
        "",
        "The references are reconstructed preserved response prefixes: original output IDs and EOS "
        "were not archived; no EOS was appended. Full-vocabulary T=1/T=0.6 probabilities are not "
        "certified original truncated-sampler probabilities. Original validation selected the final "
        "prompt; it is not held-out test evidence. Repeat8 did not select these prompts and its "
        "historical request seeds differ from the original evaluation. Bootstrap intervals condition "
        "on fixed responses and exclude across-run/regeneration uncertainty.",
        "",
        "[Endpoint metrics](endpoint_summary.csv), [all fixed responses](trajectory_changes.csv), "
        "[score verification](verification.json).",
        "",
    ]
    (output / "README.md").write_text("\n".join(lines))
    return endpoints


def run(config_path, dry_run=False):
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer

    config_path = Path(config_path).resolve()
    config = tomllib.loads(config_path.read_text())
    if os.environ.get("CUDA_VISIBLE_DEVICES") != "1" or config["execution"]["physical_gpu"] != 1:
        raise ValueError("Only approved physical GPU 1 may be exposed")
    torch.set_num_threads(config["execution"]["cpu_threads"])
    model_path = Path(config["model"]["path"]).resolve()
    if model_path.name != config["model"]["revision"]:
        raise ValueError("Model snapshot revision mismatch")
    cache_root = Path(config["cache"]["run"]).resolve() if "cache" in config else None
    old_manifest = json.loads((cache_root / "manifest.json").read_text()) if cache_root else None
    cached_model = None
    if old_manifest:
        cache_plan = json.loads((cache_root / "plan.json").read_text())
        cached_kernel = cache_plan.get("kernel_sha256", cache_plan.get("analysis_source_sha256"))
        if cached_kernel != file_sha256(Path(__file__).with_name("textgrad_likelihood.py")):
            raise ValueError("Cached numerical kernel differs")
        cached_model = old_manifest.get("config", {}).get("model", cache_plan["model"])
    if old_manifest and (old_manifest["status"] != "complete" or cached_model != config["model"]):
        raise ValueError("Cache model identity or completion status differs")
    tokenizer = AutoTokenizer.from_pretrained(model_path, local_files_only=True)
    sources, endpoints, jobs = build_inputs(config, tokenizer)
    previous = {r["key"]: r for r in read_jsonl(cache_root / "score_index.jsonl")} if cache_root else {}
    work = [(j, cid, prefix) for j in jobs for cid, prefix in j["contexts"].items()]
    if len({j["row_key"] + ":" + cid for j, cid, _ in work}) != len(work):
        raise ValueError("Duplicate captured scoring context identity")
    reused = sum(j["row_key"] + ":" + cid in previous for j, cid, _ in work)
    plan = {
        "comparison_type": "candidate_origins"
        if any("response_origins" in e for e in endpoints)
        else "base_to_validation_selected_endpoint",
        "sources": sources,
        "endpoints": endpoints,
        "model": config["model"],
        "design": config["design"],
        "config_sha256": file_sha256(config_path),
        "source_sha256": file_sha256(Path(__file__)),
        "kernel_sha256": file_sha256(Path(__file__).with_name("textgrad_likelihood.py")),
        "cache_manifest_sha256": file_sha256(cache_root / "manifest.json") if cache_root else None,
        "reference_trajectories": len(jobs),
        "scoring_contexts": len(work),
        "reused_contexts": reused,
        "new_contexts": len(work) - reused,
        "input_tokens": sum(len(prefix) + len(j["response_ids"]) for j, _, prefix in work),
    }
    print(
        json.dumps({k: v for k, v in plan.items() if k not in {"sources", "endpoints"}}, indent=2), flush=True
    )
    if dry_run:
        return plan
    output = Path(config["execution"]["output"]).resolve()
    output.mkdir(parents=True, exist_ok=False)
    (output / "tokens").mkdir()
    (output / "analysis.toml").write_bytes(config_path.read_bytes())
    write_json(output / "plan.json", plan)
    write_csv(
        output / "reconstruction_audit.csv",
        [
            {
                "row_key": j["row_key"],
                "source": j["source"],
                "finish_reason": j["finish_reason"],
                "reward": j["reward"],
                "origin_id": j.get("origin_id", "0"),
                **j["audit"],
            }
            for j in jobs
        ],
    )
    manifest = {"status": "running", "physical_gpu": 1, "torch": torch.__version__}
    write_json(output / "manifest.json", manifest)
    started, cache = time.perf_counter(), {}
    try:
        model_hashes = {
            p.name: file_sha256(p)
            for p in sorted(model_path.iterdir())
            if p.is_file() and p.suffix in {".json", ".jinja", ".safetensors"}
        }
        if old_manifest and model_hashes != old_manifest["model_files_sha256"]:
            raise ValueError("Model files changed since cached execution")
        manifest["model_files_sha256"] = model_hashes
        model = None
        work.sort(
            key=lambda w: (
                w[0]["row_key"] + ":" + w[1] not in previous,
                len(w[2]) + len(w[0]["response_ids"]),
            )
        )
        for i, (job, cid, prefix) in enumerate(work, 1):
            key = job["row_key"] + ":" + cid
            target = output / "tokens" / (digest(key) + ".npz")
            if key in previous:
                record = previous[key]
                original = cached_context(record, cache_root, prefix, job["response_ids"])
                shutil.copyfile(original, target)
                metrics = record["metrics"]
            else:
                if model is None:
                    model = (
                        AutoModelForCausalLM.from_pretrained(
                            model_path,
                            dtype=torch.bfloat16,
                            attn_implementation="sdpa",
                            local_files_only=True,
                        )
                        .to("cuda:0")
                        .eval()
                    )
                    model.requires_grad_(False)
                arrays = score_context(model, prefix, job["response_ids"], config["execution"]["head_chunk"])
                np.savez_compressed(
                    target,
                    scores=arrays,
                    prompt_ids=np.asarray(prefix, dtype=np.int32),
                    response_ids=np.asarray(job["response_ids"], dtype=np.int32),
                )
                metrics = summarize_arrays(arrays)
            record = {
                "key": key,
                "metrics": metrics,
                "token_file": str(target.relative_to(output)),
                "sha256": file_sha256(target),
                "response_sha256": digest(job["response_ids"]),
                "reused": key in previous,
            }
            with (output / "score_index.jsonl").open("a") as stream:
                stream.write(json.dumps(record, allow_nan=False) + "\n")
            cache[key] = metrics
            if i % 20 == 0 or i == len(work):
                elapsed = time.perf_counter() - started
                write_json(
                    output / "progress.json", {"done": i, "total": len(work), "elapsed_seconds": elapsed}
                )
                print(f"PROGRESS {i}/{len(work)} elapsed={elapsed:.1f}s", flush=True)
        result = make_report(output, plan, jobs, cache, config["statistics"])
        proof = verify_tokens(output)
        if proof["verified_files"] != len(work) or proof["fixed_reference_trajectories"] != len(jobs):
            raise ValueError("Incomplete endpoint verification")
        write_json(output / "verification.json", proof)
        manifest.update(status="complete", verification=proof)
        manifest["origin_contrasts" if plan["comparison_type"] == "candidate_origins" else "endpoints"] = (
            result
        )
    except BaseException as error:
        manifest.update(status="failed", error=f"{type(error).__name__}: {error}")
        raise
    finally:
        manifest.update(elapsed_seconds=time.perf_counter() - started, completed_contexts=len(cache))
        write_json(output / "manifest.json", manifest)
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    run(args.config, args.dry_run)


if __name__ == "__main__":
    main()
